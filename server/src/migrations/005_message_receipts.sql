-- 005_message_receipts.sql
-- Статуси «доставлено / прочитано» для прямих діалогів.
--
-- Модель — watermark на учасника діалогу, а не прапорець на кожне повідомлення:
--   last_delivered_at — час найновішого повідомлення, яке клієнт учасника отримав;
--   last_read_at      — час найновішого повідомлення, яке учасник бачив у відкритому чаті.
--
-- Статус конкретного повідомлення відправник виводить порівнянням msg.created_at
-- з watermark'ами співрозмовника, тому на N повідомлень припадає O(1) UPDATE'ів,
-- а не N рядків у таблиці квитанцій. Наслідок: «прочитано» завжди означає
-- «доставлено» (read-водяний знак піднімає й delivered), тож неможливий стан
-- «прочитано, але не доставлено» просто не існує в даних.
--
-- Схема розрахована на direct (1:1), де в повідомлення рівно один одержувач.
-- Для групових чатів знадобиться per-recipient таблиця receipts.

ALTER TABLE conversation_participants
  ADD COLUMN IF NOT EXISTS last_delivered_at timestamptz,
  ADD COLUMN IF NOT EXISTS last_read_at timestamptz;
