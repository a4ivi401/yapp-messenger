-- Присутність: коли користувача востаннє бачили в мережі.
--
-- Онлайн-стан НЕ зберігається в БД: він похідний від живого з'єднання Socket.IO
-- і живе в пам'яті процесу (див. server/src/presence.js). Тут лежить лише
-- остання відома мітка активності — щоб після перезавантаження сторінки,
-- перезапуску сервера чи виходу користувача клієнт міг показати «востаннє …».
--
-- NULL = користувач ще жодного разу не був у мережі (наприклад, акаунт створено
-- до міграції 006 і він жодного разу не заходив після неї).
--
-- Колонка оновлюється двома шляхами:
--   1) у момент відключення останнього сокета користувача (точний час виходу);
--   2) раз на хвилину одним пакетним UPDATE для всіх онлайн-користувачів —
--      це захист від обриву мережі/падіння процесу, коли подія disconnect
--      не доходить і без пакетного запису мітка залишилася б дуже старою.
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_seen_at timestamptz;
